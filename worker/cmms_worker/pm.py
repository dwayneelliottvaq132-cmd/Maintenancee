"""Preventive-maintenance work-order generation. Mirrors com.cmms.service.PmService / PmMath."""
import calendar
import logging
from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal

log = logging.getLogger(__name__)


def add_months(d: date, months: int) -> date:
    """Same semantics as java.time.LocalDate.plusMonths (clamps to month end)."""
    m = d.month - 1 + months
    y, m = d.year + m // 12, m % 12 + 1
    return date(y, m, min(d.day, calendar.monthrange(y, m)[1]))


def next_due(base: date, frequency_type: str, interval: int) -> date | None:
    if frequency_type == "DAYS":
        return base + timedelta(days=interval)
    if frequency_type == "WEEKS":
        return base + timedelta(weeks=interval)
    if frequency_type == "MONTHS":
        return add_months(base, interval)
    return None  # METER schedules are driven by readings, not dates


@dataclass
class Schedule:
    id: int
    title: str
    frequency_type: str
    interval_value: int
    next_due: date | None
    next_meter: Decimal | None
    lead_days: int
    active: bool
    asset_meter: Decimal | None = None


def is_due(s: Schedule, today: date) -> bool:
    if not s.active:
        return False
    if s.frequency_type == "METER":
        return s.next_meter is not None and s.asset_meter is not None and s.asset_meter >= s.next_meter
    return s.next_due is not None and s.next_due - timedelta(days=s.lead_days) <= today


SELECT_SCHEDULES = """
    SELECT p.id, p.title, p.frequency_type, p.interval_value, p.next_due, p.next_meter, p.lead_days, p.active,
           p.asset_id, p.instruction_id, p.priority, p.default_assignee_id, a.meter_reading AS asset_meter, a.location_id
      FROM pm_schedules p JOIN assets a ON a.id = p.asset_id
     WHERE p.active
       AND NOT EXISTS (SELECT 1 FROM work_orders w WHERE w.pm_schedule_id = p.id
                        AND w.status NOT IN ('SIGNED_OFF','CANCELLED'))
     ORDER BY p.id
"""


def generate_due(conn, today: date | None = None, dry_run: bool = False) -> list[str]:
    """Create one PM work order for every due schedule that has no open work order. Idempotent."""
    today = today or date.today()
    created: list[str] = []
    rows = conn.execute(SELECT_SCHEDULES).fetchall()
    for r in rows:
        s = Schedule(r["id"], r["title"], r["frequency_type"], r["interval_value"], r["next_due"],
                     r["next_meter"], r["lead_days"], r["active"], r["asset_meter"])
        if not is_due(s, today):
            continue
        if dry_run:
            created.append(f"(dry run) {s.title}")
            continue
        with conn.transaction():
            number = "WO-%d" % conn.execute("SELECT nextval('work_order_number_seq') AS n").fetchone()["n"]
            due = today + timedelta(days=7) if s.frequency_type == "METER" else s.next_due
            status = "ASSIGNED" if r["default_assignee_id"] else "OPEN"
            wo_id = conn.execute(
                """INSERT INTO work_orders (number, title, description, type, priority, status, asset_id, location_id,
                                            pm_schedule_id, instruction_id, due_date)
                   VALUES (%s, %s, %s, 'PM', %s, %s, %s, %s, %s, %s, %s)
                   ON CONFLICT DO NOTHING RETURNING id""",
                (number, f"PM: {s.title}", f'Preventive maintenance generated from schedule "{s.title}".',
                 r["priority"], status, r["asset_id"], r["location_id"], s.id, r["instruction_id"], due),
            ).fetchone()
            if wo_id is None:  # another process created it concurrently (unique open-PM index)
                continue
            wo_id = wo_id["id"]
            if r["default_assignee_id"]:
                conn.execute("INSERT INTO wo_assignments (work_order_id, user_id) VALUES (%s, %s)",
                             (wo_id, r["default_assignee_id"]))
            conn.execute("UPDATE pm_schedules SET last_generated_at = now() WHERE id = %s", (s.id,))
            conn.execute("INSERT INTO audit_log (entity, entity_id, action, details) VALUES ('work_order', %s, 'CREATE', %s)",
                         (wo_id, f"{number} generated by PM worker"))
        created.append(number)
        log.info("Created %s for schedule %s (%s)", number, s.id, s.title)
    return created
